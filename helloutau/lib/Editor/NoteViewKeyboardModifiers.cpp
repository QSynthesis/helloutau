#include "NoteViewKeyboardModifiers.h"

#include <QtCore/QCoreApplication>

namespace hello::daw {

    const KeyboardModifierScheme &NoteViewKeyboardModifiers::scheme() {
        constexpr auto ctrl = Qt::ControlModifier;
        constexpr auto alt = Qt::AltModifier;
        constexpr auto shift = Qt::ShiftModifier;
        constexpr auto none = Qt::NoModifier;
        // The drag that zooms, an operation of every left drag scene
        const KeyboardModifierScheme::Operation zoom{DragZoom, {DragZoomAxisLock}};
        static const KeyboardModifierScheme scheme(
            "noteView", "hello::daw::NoteViewKeyboardModifiers",
            QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Note Area"),
            {
                {VerticalScroll, "verticalScroll",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Wheel: Scroll Vertically"),
                 none},
                {HorizontalScroll, "horizontalScroll",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Wheel: Scroll Horizontally"),
                 shift},
                {TimeZoom, "timeZoom",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Wheel: Zoom Time"),
                 ctrl},
                {KeyZoom, "keyZoom",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Wheel: Zoom Keys"),
                 ctrl | shift},
                {SelectNote, "selectNote",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Click Note: Select"),
                 none},
                {ToggleNote, "toggleNote",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Click Note: Toggle"),
                 ctrl},
                {ExtendNotes, "extendNotes",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Click Note: Extend"),
                 shift},
                {MoveNotes, "moveNotes",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Drag Note: Move"),
                 none},
                {PlainLength, "plainLength",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Drag Note End: Fill with Rest"),
                 none},
                {FreeLength, "freeLength",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Drag Note End: Move Next Notes"),
                 shift},
                {TakeFromNextNote, "takeFromNextNote",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Drag Note End: Take from Next Note"),
                 ctrl},
                {SelectPoint, "selectPoint",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Click Point: Select"),
                 none},
                {TogglePoint, "togglePoint",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Click Point: Toggle"),
                 ctrl},
                {MovePoints, "movePoints",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Drag Point: Move"),
                 none},
                {ClearSelection, "clearSelection",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Click Blank: Clear Selection"),
                 none},
                {ReplaceBand, "replaceBand",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Band: Select"), none},
                {AddToBand, "addToBand",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Band: Add"), shift},
                {ToggleBand, "toggleBand",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Band: Toggle"), ctrl},
                {PlainDraw, "plainDraw",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Pen: Draw"), none},
                {FillDraw, "fillDraw",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Pen: Draw Filling with Rest"),
                 shift},
                {DrawPitch, "drawPitch",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Pitch Tool: Draw"),
                 none},
                {ErasePitch, "erasePitch",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Pitch Tool: Erase"),
                 none},
                {DragVibrato, "dragVibrato",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Drag Vibrato: Edit"),
                 none},
                {DragZoom, "dragZoom",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Drag: Zoom"),
                 ctrl | alt},
                {DragZoomAxisLock, "dragZoomAxisLock",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers", "Zoom: Lock Direction"),
                 shift},
                {DisableNoteSnap, "disableNoteSnap",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Toggle: Disable Note Snap"),
                 alt},
                {PointSnapTime, "pointSnapTime",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Drag Point: Snap to Other Points"),
                 shift},
                {PointSnapPitch, "pointSnapPitch",
                 QT_TRANSLATE_NOOP("hello::daw::NoteViewKeyboardModifiers",
                                   "Drag Point: Snap Pitch"),
                 ctrl},
            },
            {
                {WheelScene,
                 {{VerticalScroll}, {HorizontalScroll}, {TimeZoom}, {KeyZoom}}},
                {NoteClickScene, {{SelectNote}, {ToggleNote}, {ExtendNotes}}},
                {NoteDragScene, {{MoveNotes}, zoom}},
                {NoteEndDragScene,
                 {{PlainLength, {DisableNoteSnap}},
                  {FreeLength, {DisableNoteSnap}},
                  {TakeFromNextNote, {DisableNoteSnap}},
                  zoom}},
                {PointClickScene, {{SelectPoint}, {TogglePoint}}},
                {PointDragScene, {{MovePoints, {PointSnapTime, PointSnapPitch}}, zoom}},
                {BlankClickScene, {{ClearSelection}}},
                {BandDragScene, {{ReplaceBand}, {AddToBand}, {ToggleBand}, zoom}},
                {DrawClickScene,
                 {{PlainDraw, {DisableNoteSnap}}, {FillDraw, {DisableNoteSnap}}}},
                {DrawDragScene,
                 {{PlainDraw, {DisableNoteSnap}}, {FillDraw, {DisableNoteSnap}}, zoom}},
                {SpanScene, {{ReplaceBand}, {AddToBand}, {ToggleBand}}},
                {PitchDrawScene, {{DrawPitch}, zoom}},
                {PitchEraseScene, {{ErasePitch}}},
                {VibratoDragScene, {{DragVibrato}, zoom}},
            });
        return scheme;
    }

}
